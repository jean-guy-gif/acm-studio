// Ce qu'un scénario a en commun : le type et la commune principale ; chaque bien le précise.
type ListingSeed = Omit<DemoListing, 'scenario' | 'propertyType' | 'photos'> & {
  photos?: string[];
};

const seed =
  (
    scenario: DemoScenarioId,
    propertyType: DemoListing['propertyType'],
    pool: string[],
    photosPer: (index: number) => string[],
  ) =>
  (listings: ListingSeed[]): DemoListing[] =>
    listings.map((listing, index) => ({
      ...listing,
      scenario,
      propertyType,
      photos: listing.photos ?? photosPer(index).map((name) => pool[Number(name)] ?? name),
    }));

// Les photos libres de droits, par famille (`public/demo/photos`, sources dans docs/DEMO.md).
export const DEMO_PHOTO_POOLS = {
  apartment: Array.from(
    { length: 8 },
    (_, i) => `appartement-${String(i + 1).padStart(2, '0')}.jpg`,
  ),
  house: Array.from({ length: 8 }, (_, i) => `maison-${String(i + 1).padStart(2, '0')}.jpg`),
  villa: Array.from({ length: 8 }, (_, i) => `villa-${String(i + 1).padStart(2, '0')}.jpg`),
} as const;

// 2 à 4 photos par bien, en tournant dans la famille : la première distingue le bien, les
// suivantes montrent l'intérieur.
const rotate = (size: number) => (index: number) => {
  const count = 2 + (index % 3); // 2, 3, 4, 2, 3, 4…
  return Array.from({ length: count }, (_, k) => String((index + k) % size));
};

