// « €700k », « €1.2m » : un budget arrondi, en anglais.
function englishBudget(value: number): string {
  return value >= 1_000_000
    ? `€${formatNumber(value / 1_000_000, { language: 'en' })}m`
    : `€${formatNumber(value / 1_000, { language: 'en' })}k`;
}

// 1st, 2nd, 3rd, 4th… 11th, 12th, 13th, 21st.
function englishOrdinal(rank: number): string {
  const lastTwo = rank % 100;
  if (lastTwo >= 11 && lastTwo <= 13) return `${rank}th`;
  const suffix = { 1: 'st', 2: 'nd', 3: 'rd' }[rank % 10] ?? 'th';
  return `${rank}${suffix}`;
}

// Mission 148 B — « dont N vus ensemble » (M112), quand des concurrents hors Live entrent au calcul.
function seenTogetherEn(count: number, seen: number | null): string {
  return seen != null && seen < count ? `, ${seen} of which we viewed together` : '';
}

